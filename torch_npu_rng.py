"""Versioned seed/counter metadata for the synchronous single-device NPU RNG.

Philox values are generated by resident_rng.c, never by this host module.
"""
import operator
import struct
import torch

_FORMAT = '<8sQQ'
_MAGIC = b'NPURNG01'
_LIMIT = (1 << 64)-1


def permutation_size(n, dtype):
    """Bound indices by exact dtype representation and the existing device sorter."""
    n = operator.index(n)
    if dtype in (torch.float16, torch.bfloat16, torch.float32):
        limit = {torch.float16:2049, torch.bfloat16:257, torch.float32:16777217}[dtype]
    elif dtype in (torch.int8, torch.uint8, torch.int16, torch.int32, torch.int64):
        limit = torch.iinfo(dtype).max+1
    else:
        raise ValueError('NPU randperm requires a supported real numeric dtype')
    if not 0 <= n <= min(limit, 16777216):
        raise ValueError('NPU randperm exceeds its exact dtype or 16777216-element sort bound')
    return n


def integer_range(low=0, high=None):
    """Raw signed-low/range/rejection metadata, never random tensor payload."""
    low = operator.index(low)
    high = (1 << 63) if high is None else operator.index(high)
    if not -(1 << 63) <= low < high <= (1 << 63):
        raise ValueError('NPU integer RNG requires ordered signed INT64 bounds')
    span = high-low
    return low & _LIMIT, span & _LIMIT, (1 << 64) % span


class RNGState:
    def __init__(self, seed):
        self.manual_seed(seed)

    def manual_seed(self, seed):
        seed = int(seed)
        if not -(1 << 63) <= seed <= _LIMIT:
            raise RuntimeError('NPU seed must fit the PyTorch 64-bit seed range')
        self.seed, self.offset = seed & _LIMIT, 0

    def reserve(self, count):
        count = operator.index(count)
        if count < 1 or self.offset+count > _LIMIT:
            raise RuntimeError('NPU RNG counter exhausted; reseed before generating more values')
        start = self.offset
        self.offset += count
        return self.seed, start

    def get_state(self):
        return torch.tensor(list(struct.pack(_FORMAT, _MAGIC, self.seed, self.offset)), dtype=torch.uint8, device='cpu')

    def set_state(self, state):
        if (not isinstance(state, torch.Tensor) or state.device.type != 'cpu' or state.dtype != torch.uint8 or
                state.ndim != 1 or state.numel() != struct.calcsize(_FORMAT) or not state.is_contiguous()):
            raise ValueError('NPU RNG state must be a contiguous 24-byte CPU ByteTensor')
        magic, seed, offset = struct.unpack(_FORMAT, bytes(state.tolist()))
        if magic != _MAGIC:
            raise ValueError('Unknown NPU RNG state version')
        self.seed, self.offset = seed, offset
